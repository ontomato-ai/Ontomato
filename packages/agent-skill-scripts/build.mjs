// Build every self-contained agent skill script from the single source in this package.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const directory = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(directory, "../..");
const check = process.argv.includes("--check");
const banner = "// Generated by packages/agent-skill-scripts/build.mjs; do not edit.";
const outputs = [
  ["entries/ontology-query.mjs", "agent-skills/ontology-query/scripts/ontomato.mjs"],
  ["entries/data-retrieval-dataset.mjs", "agent-skills/data-retrieval/scripts/dataset.mjs"],
  ["entries/ontology-generation.mjs", "agent-skills/ontology-generation/scripts/generation.mjs"],
  ["entries/metricview-generation.mjs", "agent-skills/metricview-generation/scripts/generation.mjs"],
  ["shared/client.mjs", "agent-skills/ontomato-analyst/client.mjs"],
  ["shared/client.mjs", "agent-skills/ontomato-app-builder/scripts/client.mjs"],
  ["shared/client.mjs", "agent-skills/ontomato-ontomap-builder/client.mjs"],
];

const stale = [];
for (const [entry, output] of outputs) {
  const outfile = path.join(repo, output);
  const options = {
    entryPoints: [path.join(directory, "src", entry)],
    outfile,
    bundle: true,
    platform: "node",
    target: "node24",
    format: "esm",
    minify: true,
    legalComments: "none",
    banner: { js: banner },
    logLevel: "silent",
  };
  if (check) {
    const result = await build({ ...options, write: false });
    const generated = result.outputFiles[0].text;
    const actual = fs.existsSync(outfile) ? fs.readFileSync(outfile, "utf8") : "";
    if (actual !== generated) stale.push(output);
  } else {
    fs.mkdirSync(path.dirname(outfile), { recursive: true });
    await build(options);
  }
}
if (stale.length) {
  console.error("Generated agent skill scripts are stale:\n" + stale.map(name => `  ${name}`).join("\n"));
  process.exitCode = 1;
}
