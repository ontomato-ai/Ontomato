// Rebuild the committed runtime packages of the three chart skills from their single source before publishing.
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const directory = path.dirname(fileURLToPath(import.meta.url));
const skills = path.resolve(process.argv[2] ?? path.join(directory, "../skills/executable/visualization"));
const banner = "// Generated by packages/workbench-server/chart-skill/build.mjs; do not edit.";
const zod = path.dirname(createRequire(import.meta.url).resolve("zod/package.json"));

for (const name of ["echarts", "leaflet", "admin-choropleth-map"]) {
  await build({
    entryPoints: [path.join(directory, "entries", `${name}.mjs`)],
    outfile: path.join(skills, name, "scripts/index.mjs"),
    bundle: true, platform: "node", target: "node24", format: "esm", minify: true,
    legalComments: "none", banner: { js: banner }, logLevel: "info",
  });
  // The bundle carries zod; its licence travels with the standalone package.
  fs.mkdirSync(path.join(skills, name, "licenses"), { recursive: true });
  fs.copyFileSync(path.join(zod, "LICENSE"), path.join(skills, name, "licenses/zod-LICENSE.txt"));
  // The choropleth package carries the platform boundary resource and its provenance.
  if (name === "admin-choropleth-map")
    fs.copyFileSync(path.join(directory, "../../contracts/chart-maps/README.md"),
      path.join(skills, name, "licenses/china-provinces-README.md"));
}
