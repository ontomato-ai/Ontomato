import type { AgentTool, AgentToolResult } from "../../../core/agent-loop/types";
import { errorMessage, isRecord, postDataEngine, type DataEngineCaller } from "./data-engine";
import type { DeepAnalysisArtifactStore } from "../task/artifacts";
import { tApp } from "../../../i18n";

/** Shown as the service of a metric view call in the trajectory; the metric view name is the tool. */
const METRIC_VIEW_SERVICE_NAME = "MetricView";

/** Only metric views whose Function reads data are callable: the loop never writes through this tool. */
const READ_OPERATION = "OPERATION_READ";

interface LoopMetricViewDeps extends DataEngineCaller {
  selectedMetricViewIds: readonly string[];
  signal: AbortSignal;
  trajectory: Pick<DeepAnalysisArtifactStore, "start" | "settle">;
}

interface LoopMetricViewDefinition {
  id: string;
  name: string;
  description: string;
  parameters: Array<{ name: string; type?: string; description?: string }>;
}

const textResult = (text: string): AgentToolResult => ({ content: [{ type: "text", text }] });

function toDefinition(metricView: unknown): LoopMetricViewDefinition | null {
  if (!isRecord(metricView) || typeof metricView.id !== "string") return null;
  const fn = isRecord(metricView.function) ? metricView.function : {};
  if (fn.operation !== READ_OPERATION) return null;
  // A static metric view runs with the values saved in it; only a general one takes parameters.
  const parameters = metricView.type === "GENERAL" && Array.isArray(fn.parameters) ? fn.parameters.filter(isRecord) : [];
  return {
    id: metricView.id,
    name: typeof metricView.name === "string" ? metricView.name : metricView.id,
    description: [metricView.description, fn.logic].filter((part) => typeof part === "string" && part.trim()).join("\n"),
    parameters: parameters.map((parameter) => ({
      name: String(parameter.name ?? ""),
      ...(typeof parameter.type === "string" ? { type: parameter.type } : {}),
      ...(typeof parameter.description === "string" ? { description: parameter.description } : {}),
    })),
  };
}

/**
 * Exposes the agent's selected, currently published read-only metric views to the loop supervisor. A call runs the
 * metric view's Function directly through the data engine with the caller's own credentials and data permissions, so
 * an answer that a saved program already defines, such as a knowledge search over a vector attribute, costs one call
 * instead of a query generated by the data system.
 */
export async function assembleLoopMetricViewCapability(deps: LoopMetricViewDeps) {
  const none = { prompt: "", supervisorTools: [] as AgentTool[] };
  if (deps.selectedMetricViewIds.length === 0) return none;

  let metricViews: LoopMetricViewDefinition[];
  try {
    const published = (await postDataEngine(deps, "/metricView/queryList", { status: "PUBLISHED" }, deps.signal)).data;
    const selected = new Set(deps.selectedMetricViewIds);
    metricViews = (Array.isArray(published) ? published : [])
      .map(toDefinition)
      .filter((metricView): metricView is LoopMetricViewDefinition => !!metricView && selected.has(metricView.id));
  } catch (error) {
    if (deps.signal.aborted) throw error;
    const activityId = deps.trajectory.start("external_tool", { serviceName: METRIC_VIEW_SERVICE_NAME });
    deps.trajectory.settle(activityId, "failed", {
      error: tApp("analysis.loop.metric-views.unavailable", { message: errorMessage(error) }),
    });
    return none;
  }
  if (metricViews.length === 0) return none;

  const byId = new Map(metricViews.map((metricView) => [metricView.id, metricView]));
  const executeMetricView: AgentTool = {
    name: "execute_metric_view",
    description: tApp("analysis.loop.metric-views.tool"),
    parameters: {
      type: "object",
      properties: {
        metric_view_id: { type: "string", enum: metricViews.map((metricView) => metricView.id) },
        parameters: { type: "object", description: tApp("analysis.loop.metric-views.parameters") },
      },
      required: ["metric_view_id", "parameters"],
    },
    async execute(toolCallId, params, signal) {
      const metricView = typeof params.metric_view_id === "string" ? byId.get(params.metric_view_id) : undefined;
      const toolArguments = isRecord(params.parameters) ? params.parameters : {};
      const activityId = deps.trajectory.start("external_tool", {
        serviceName: METRIC_VIEW_SERVICE_NAME,
        toolName: metricView?.name ?? String(params.metric_view_id ?? ""),
        toolArguments,
        toolCallId,
      });
      if (!metricView) {
        const message = tApp("analysis.loop.metric-views.unknown", {
          metricViewId: String(params.metric_view_id ?? ""),
        });
        deps.trajectory.settle(activityId, "failed", { error: message });
        return textResult(message);
      }
      const requestSignal = signal || deps.signal;
      try {
        const { success: _success, ...result } = await postDataEngine(
          deps,
          "/metricView/execute",
          { id: metricView.id, param: toolArguments },
          requestSignal
        );
        deps.trajectory.settle(activityId, "completed");
        // data is the program's result; truncated, rowLimit and truncationHint come along when a query was cut.
        return textResult(JSON.stringify(result));
      } catch (error) {
        const message = errorMessage(error);
        deps.trajectory.settle(activityId, requestSignal.aborted ? "cancelled" : "failed", { error: message });
        if (requestSignal.aborted) throw error;
        return textResult(tApp("analysis.loop.metric-views.failed", { message }));
      }
    },
  };

  return {
    prompt: tApp("analysis.loop.metric-views.prompt", { metricViews: JSON.stringify(metricViews) }),
    supervisorTools: [executeMetricView],
  };
}
