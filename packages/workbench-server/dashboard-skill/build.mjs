import fs from "node:fs";
import path from "node:path";
import {createRequire} from "node:module";
import {fileURLToPath} from "node:url";
import {build} from "esbuild";
const directory=path.dirname(fileURLToPath(import.meta.url));
const output=path.resolve(process.argv[2]??path.join(directory,"../skills/pages/dashboard-pages"));
await build({entryPoints:[path.join(directory,"cli.mjs")],outfile:path.join(output,"scripts/dashboard-pages.mjs"),bundle:true,platform:"node",target:"node24",format:"esm",minify:true,legalComments:"none",banner:{js:"// Generated by packages/workbench-server/dashboard-skill/build.mjs; do not edit."},logLevel:"info"});
const zod=path.dirname(createRequire(import.meta.url).resolve("zod/package.json"));
fs.mkdirSync(path.join(output,"licenses"),{recursive:true});
fs.copyFileSync(path.join(zod,"LICENSE"),path.join(output,"licenses/zod-LICENSE.txt"));
